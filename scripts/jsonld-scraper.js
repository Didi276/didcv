export const TOTAL = ENTREPRISES_2000.length

async function main() {
  const START = parseInt(process.env.START || '0')
  const END = parseInt(process.env.END || '999')
  const tranche = ENTREPRISES_2000.slice(START, END)
  console.log(`🔍 JSON-LD Scraper — ${tranche.length} entreprises (${START} à ${END})\n`)
  let totalOffres = 0
  let entreprisesOK = 0
  for (const { domaine, nom } of tranche) {
    if (domainesDejaGeres.has(domaine) ||
        domainesDejaGeres.has('www.' + domaine)) {
      console.log(`  ⏭️ ${nom}: déjà géré par ATS scraper`)
      continue
    }
    console.log(`⏳ ${nom} (${domaine})...`)
    const offres = await scraperEntrepriseJsonLD(domaine, nom)
    if (offres.length === 0) {
      console.log(`  ❌ ${nom}: 0 offres JSON-LD`)
      continue
    }
    const uniques = offres.filter((o, i, self) =>
      i === self.findIndex(t => t.hash === o.hash)
    )
    const { error } = await supabase
      .from('offres_directes')
      .upsert(uniques, { onConflict: 'hash', ignoreDuplicates: false })
    if (!error) {
      console.log(`  ✅ ${nom}: ${uniques.length} offres JSON-LD`)
      totalOffres += uniques.length
      entreprisesOK++
    }
    await sleep(1000)
  }
  console.log(`\n🎉 Terminé: ${entreprisesOK} entreprises, ${totalOffres} offres JSON-LD`)
}

main().catch(console.error)
