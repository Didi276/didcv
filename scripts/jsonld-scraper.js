async function extractJobPostings(url, entrepriseNom) {
  try {
    const controller = new AbortController()
    const timeout = setTimeout(() => controller.abort(), 8000)
    const r = await fetch(url, {
      signal: controller.signal,
      headers: {
        'User-Agent': 'DidJob-Aggregator/1.0 (contact@did-job.com)',
        'Accept': 'text/html,application/xhtml+xml',
        'Accept-Language': 'fr-FR,fr;q=0.9'
      }
    })
    clearTimeout(timeout)
    if (!r.ok) return []
    const html = await r.text()
    const jsonldRegex = /<script[^>]+type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi
    const offres = []
    let match
    while ((match = jsonldRegex.exec(html)) !== null) {
      try {
        const data = JSON.parse(match[1].trim())
        const items = Array.isArray(data) ? data : [data]
        for (const item of items) {
          if (item['@type'] !== 'JobPosting') continue
          const titre = item.title || item.name || ''
          if (!titre || titre.length < 3) continue
          const loc = item.jobLocation
          let lieu = 'France'
          if (loc) {
            const addr = Array.isArray(loc) ? loc[0]?.address : loc?.address
            if (addr) {
              lieu = [addr.addressLocality, addr.addressRegion, addr.addressCountry]
                .filter(Boolean).join(', ')
            }
          }
          let salaire = ''
          if (item.baseSalary?.value) {
            const val = item.baseSalary.value
            const montant = typeof val === 'object' ? val.value || val.minValue : val
            const devise = item.baseSalary.currency || 'EUR'
            if (montant) salaire = `${montant} ${devise}`
          }
          const datePosted = item.datePosted ?
            new Date(item.datePosted).toISOString() :
            new Date().toISOString()
          const description = (item.description || '')
            .replace(/<[^>]*>/g, '')
            .replace(/&nbsp;/g, ' ')
            .replace(/&amp;/g, '&')
            .slice(0, 800)
          const urlCandidature = item.url || url
          const nomEntreprise = item.hiringOrganization?.name || entrepriseNom
          offres.push({
            titre: titre.trim(),
            entreprise: nomEntreprise,
            lieu,
            description,
            url_candidature: urlCandidature,
            date_publication: datePosted,
            type_contrat: item.employmentType || '',
            departement: item.occupationalCategory || '',
            salaire,
            ats_source: 'jsonld',
            hash: Buffer.from(`${titre.trim()}-${nomEntreprise}-${datePosted.slice(0,10)}`).toString('base64').slice(0, 32),
            actif: true,
            date_scraping: new Date().toISOString()
          })
        }
      } catch {}
    }
    return offres
  } catch { return [] }
}

async function parseSitemap(sitemapUrl) {
  try {
    const controller = new AbortController()
    const timeout = setTimeout(() => controller.abort(), 10000)
    const r = await fetch(sitemapUrl, {
      signal: controller.signal,
      headers: { 'User-Agent': 'DidJob-Aggregator/1.0 (contact@did-job.com)' }
    })
    clearTimeout(timeout)
    if (!r.ok) return []
    const xml = await r.text()
    const urls = []
    const sitemapRegex = /<sitemap>[\s\S]*?<loc>(.*?)<\/loc>/gi
    let match
    while ((match = sitemapRegex.exec(xml)) !== null) {
      const nestedUrl = match[1].trim()
      if (/job|emploi|career|offre|recrutement|poste/i.test(nestedUrl)) {
        const nestedUrls = await parseSitemap(nestedUrl)
        urls.push(...nestedUrls)
      }
    }
    const urlRegex = /<url>[\s\S]*?<loc>(.*?)<\/loc>/gi
    while ((match = urlRegex.exec(xml)) !== null) {
      const url = match[1].trim()
      if (/\/(job|emploi|offre|career|poste|recrutement|position|vacancy|annonce|jobs)[\/-]/i.test(url) ||
          /\/(job|emploi|offre|career|poste|recrutement)\/[^\/]+\/?$/.test(url)) {
        urls.push(url)
      }
    }
    return [...new Set(urls)].slice(0, 500)
  } catch { return [] }
}

async function scraperEntrepriseJsonLD(domaine, nom) {
  // URLs de pages carrières à tester directement
  const careerPages = [
    `https://${domaine}/careers`,
    `https://${domaine}/careers/`,
    `https://www.${domaine}/careers`,
    `https://${domaine}/emplois`,
    `https://${domaine}/offres-emploi`,
    `https://${domaine}/offres-d-emploi`,
    `https://${domaine}/recrutement`,
    `https://${domaine}/jobs`,
    `https://${domaine}/jobs/`,
    `https://www.${domaine}/jobs`,
    `https://${domaine}/fr/careers`,
    `https://${domaine}/fr/jobs`,
    `https://${domaine}/fr/offres`,
    `https://careers.${domaine}`,
    `https://jobs.${domaine}`,
    `https://recrutement.${domaine}`,
    `https://emploi.${domaine}`,
    `https://carrieres.${domaine}`,
  ]

  // D'abord essayer les pages carrières directement
  // (plus rapide que le sitemap pour la plupart des cas)
  let toutesOffres = []
  const vus = new Set()

  for (const page of careerPages) {
    const offres = await extractJobPostings(page, nom)
    for (const o of offres) {
      if (!vus.has(o.hash)) {
        vus.add(o.hash)
        toutesOffres.push(o)
      }
    }
    if (toutesOffres.length > 0) {
      console.log(`  ✅ JSON-LD trouvé sur ${page}`)
      break
    }
    await sleep(200)
  }

  // Si rien trouvé via pages carrières, essayer le sitemap
  if (toutesOffres.length === 0) {
    const sitemapUrls = [
      `https://${domaine}/sitemap.xml`,
      `https://www.${domaine}/sitemap.xml`,
    ]
    let jobUrls = []
    for (const sitemapUrl of sitemapUrls) {
      const urls = await parseSitemap(sitemapUrl)
      if (urls.length > 0) {
        jobUrls = urls
        console.log(`  📄 ${nom}: ${urls.length} URLs dans sitemap`)
        break
      }
      await sleep(300)
    }
    for (const url of jobUrls.slice(0, 50)) {
      const offres = await extractJobPostings(url, nom)
      for (const o of offres) {
        if (!vus.has(o.hash)) {
          vus.add(o.hash)
          toutesOffres.push(o)
        }
      }
      await sleep(200)
    }
  }

  return toutesOffres
}

