// Cache en mémoire (instance chaude Vercel). FUN-MOOC bouge lentement.
let CACHE = { at: 0, data: null }
const TTL = 1000 * 60 * 60 * 6 // 6 heures

function withTimeout(promise, ms) {
  return Promise.race([
    promise,
    new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms)),
  ])
}

// Associe un cours FUN-MOOC à l'une des 10 catégories de la page.
function mapCategorie(titreRaw) {
  const t = (titreRaw || '').toLowerCase()
  const has = (re) => re.test(t)
  if (has(/sant[ée]|m[ée]dic|soin|infirm|pharma|cliniq|maladie|patient|nutrition|psychi|handicap|m[ée]dico/)) return ['Santé', '🩺']
  if (has(/anglais|langue|espagnol|allemand|chinois|fran[çc]ais langue|\bfle\b|english/)) return ['Langues', '🗣️']
  if (has(/num[ée]riq|informatiq|programm|\bcode\b|codage|d[ée]veloppe|data|donn[ée]es|python|\bweb\b|cyber|intelligence artificielle|\bia\b|logiciel|algorith|r[ée]seau informatique|blockchain|robot/)) return ['Tech & Dev', '💻']
  if (has(/marketing|communicat|r[ée]seaux sociaux|m[ée]dia|publicit|journalis/)) return ['Marketing', '📈']
  if (has(/vente|commerc|client|n[ée]goci|business develop|relation client/)) return ['Commercial', '💼']
  if (has(/droit|juridiq|fiscal|comptab|financ|budget|[ée]conomie|mon[ée]taire|banc|assurance|gestion financi|march[ée]s/)) return ['Finance', '💶']
  if (has(/manage|ressources humaines|\brh\b|leadership|[ée]quipe|gestion de projet|agile|scrum|encadr/)) return ['RH & Management', '👔']
  if (has(/entrepreneur|cr[ée]ation d|cr[ée]er son|startup|innovation|business model|lancer son/)) return ['Entrepreneuriat', '🚀']
  if (has(/prise de parole|confiance|stress|gestion du temps|cr[ée]ativit|apprendre|m[ée]moire|soft skill|d[ée]veloppement personnel|motivation/)) return ['Soft Skills', '🧩']
  return ['Reconversion', '🎓']
}

function motsCles(titre) {
  return (titre || '')
    .toLowerCase()
    .replace(/[^a-zàâçéèêëîïôûùüÿñæœ\s]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 4)
    .slice(0, 6)
}

async function fetchFunMooc() {
  const base = 'https://www.fun-mooc.fr/api/v1.0/courses/'
  const PAGE = 50
  let offset = 0
  let total = Infinity
  const out = []
  const vus = new Set()
  while (offset < total && offset < 1000) {
    let d
    try {
      const r = await withTimeout(
        fetch(`${base}?limit=${PAGE}&offset=${offset}`, { headers: { Accept: 'application/json' } }),
        6000
      )
      d = await r.json()
    } catch { break }
    total = d?.meta?.total_count ?? out.length
    const objs = d?.objects || []
    if (objs.length === 0) break
    for (const o of objs) {
      const code = o.code || o.id
      if (!code || vus.has(code)) continue
      vus.add(code)
      // on ne garde que les cours accessibles gratuitement
      const runs = o.course_runs || []
      const gratuit = runs.length === 0 || runs.some(r => !r.offer || r.offer === 'free' || r.price == null)
      if (!gratuit) continue
      const [categorie, emoji] = mapCategorie(o.title)
      out.push({
        id: 'fun-' + code,
        titre: o.title,
        organisme: 'FUN-MOOC',
        duree: o.effort || o.duration || 'En ligne',
        format: 'En ligne',
        niveau: 'Tous niveaux',
        prix: 'Gratuit',
        lien: 'https://www.fun-mooc.fr' + (o.absolute_url || ''),
        description: o.introduction || 'MOOC universitaire gratuit en français. Accès libre au contenu, certificat en option.',
        tags: [categorie.toLowerCase(), ...motsCles(o.title)],
        categorie,
        emoji,
        certifiant: false,
      })
    }
    offset += PAGE
  }
  return out
}

async function computeFormations() {
  let fun = []
  try { fun = await fetchFunMooc() } catch { fun = [] }
  // socle curé d'abord, puis FUN-MOOC
  return [...CURATED, ...fun]
}

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*')

  if (CACHE.data && Date.now() - CACHE.at < TTL) {
    res.setHeader('X-Cache', 'HIT')
    return res.status(200).json({ formations: CACHE.data, total: CACHE.data.length })
  }

  try {
    const formations = await computeFormations()
    CACHE = { at: Date.now(), data: formations }
    res.setHeader('X-Cache', 'MISS')
    return res.status(200).json({ formations, total: formations.length })
  } catch (e) {
    if (CACHE.data) return res.status(200).json({ formations: CACHE.data, total: CACHE.data.length })
    return res.status(200).json({ formations: CURATED, total: CURATED.length })
  }
}
