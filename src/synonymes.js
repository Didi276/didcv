export function expandQuery(query) {
  const normalize = (str) => str
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .trim()

  const queryNorm = normalize(query)
  const mots = queryNorm.split(' ').filter(m => m.length > 2)

  const termes = new Set([queryNorm, ...mots])

  for (const [terme, syns] of Object.entries(SYNONYMES)) {
    const termeNorm = normalize(terme)
    if (queryNorm.includes(termeNorm) || termeNorm.includes(queryNorm)) {
      syns.forEach(s => termes.add(normalize(s)))
    }
  }

  return [...termes]
}
